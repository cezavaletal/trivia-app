CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(50) NOT NULL DEFAULT 'ROLE_PLAYER',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT,
    icono VARCHAR(50) DEFAULT 'help-circle' NOT NULL,
    color VARCHAR(20) DEFAULT '#3B82F6' NOT NULL,
    is_active BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS preguntas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL,
    enunciado TEXT NOT NULL,
    dificultad VARCHAR(50) DEFAULT 'MEDIA' NOT NULL,
    explicacion TEXT,
    is_active BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_preguntas_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id)
);

CREATE TABLE IF NOT EXISTS opciones_respuesta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta_id BIGINT NOT NULL,
    texto TEXT NOT NULL,
    es_correcta BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_opciones_pregunta FOREIGN KEY (pregunta_id) REFERENCES preguntas (id)
);

CREATE TABLE IF NOT EXISTS partidas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    categoria_id BIGINT,
    modo VARCHAR(50) NOT NULL,
    estado VARCHAR(50) DEFAULT 'IN_PROGRESS' NOT NULL,
    puntaje_total INT DEFAULT 0 NOT NULL,
    aciertos INT DEFAULT 0 NOT NULL,
    errores INT DEFAULT 0 NOT NULL,
    racha_maxima INT DEFAULT 0 NOT NULL,
    tiempo_inicio TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    tiempo_fin TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_partidas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_partidas_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id)
);

CREATE TABLE IF NOT EXISTS respuestas_usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partida_id BIGINT NOT NULL,
    pregunta_id BIGINT NOT NULL,
    opcion_seleccionada_id BIGINT,
    es_correcta BOOLEAN DEFAULT FALSE NOT NULL,
    puntos_obtenidos INT DEFAULT 0 NOT NULL,
    tiempo_respuesta_ms INT DEFAULT 0 NOT NULL,
    racha_momento INT DEFAULT 0 NOT NULL,
    respondida_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_respuestas_partida FOREIGN KEY (partida_id) REFERENCES partidas (id),
    CONSTRAINT fk_respuestas_pregunta FOREIGN KEY (pregunta_id) REFERENCES preguntas (id),
    CONSTRAINT fk_respuestas_opcion FOREIGN KEY (opcion_seleccionada_id) REFERENCES opciones_respuesta (id),
    CONSTRAINT uk_respuestas_partida_pregunta UNIQUE (partida_id, pregunta_id)
);

CREATE OR REPLACE VIEW vista_ranking_global AS
SELECT 
    ROW_NUMBER() OVER (
        ORDER BY 
            COALESCE(SUM(p.puntaje_total), 0) DESC, 
            COALESCE(SUM(p.aciertos), 0) DESC,
            u.created_at ASC
    ) AS rank,
    u.id AS usuario_id,
    u.username,
    COALESCE(SUM(p.puntaje_total), 0) AS puntaje_total,
    COUNT(p.id) AS partidas_jugadas,
    COALESCE(SUM(p.aciertos), 0) AS aciertos_totales,
    COALESCE(SUM(p.errores), 0) AS errores_totales,
    COALESCE(MAX(p.racha_maxima), 0) AS mejor_racha,
    ROUND(
        CASE 
            WHEN SUM(p.aciertos + p.errores) > 0 
            THEN (CAST(SUM(p.aciertos) AS NUMERIC) / CAST(SUM(p.aciertos + p.errores) AS NUMERIC)) * 100.0 
            ELSE 0.0 
        END, 
        2
    ) AS precision_porcentaje
FROM usuarios u
JOIN partidas p ON u.id = p.usuario_id
WHERE u.is_active = TRUE 
  AND p.estado = 'COMPLETED'
GROUP BY u.id, u.username;

